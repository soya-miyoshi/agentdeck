// Generates src/client/wire.gen.ts from the Go wire types, and fails when the committed file is
// stale. `make wire` (AGENTDECK_WRITE_WIRE=1) rewrites it. The client imports nothing else.

const wireGenPath = "../src/client/wire.gen.ts"

type wireGenType struct {
	doc string
	v   any
}

// wireGenTypes is every type that crosses the wire, in output order. A frame's example carries the
// `t` the server sends, so a literal that disagrees with the code fails here.
